# OPEN CLOSED PRINCIPLE
# Принцип открытости/закрытости (Open/Closed Principle, OCP) — это второй принцип из SOLID, который гласит, 
# что классы должны быть открыты для расширения, но закрыты для изменения.

# Что это означает на практике:
    # Открыт для расширения: мы можем расширять функциональность класса, не изменяя его исходный код.
    # Закрыт для изменения: при добавлении нового функционала мы не должны изменять существующий код, чтобы избежать поломки уже работающей системы.


# Пример нарушения OCP
# Представьте, что у нас есть класс, который рассчитывает зарплату сотрудников:


class Employee:
    def __init__(self, name, position):
        self.name = name
        self.position = position

    def calculate_salary(self):
        if self.position == "junior":
            return 50000
        elif self.position == "middle":
            return 100000
        elif self.position == "senior":
            return 150000

# !!! Проблема:
# Этот код нарушает принцип OCP, потому что, если мы захотим добавить нового сотрудника с другой позицией (например, lead), 
# нам придется изменить существующий метод calculate_salary. А изменение кода может привести к ошибкам в других местах программы.



# Исправление с использованием OCP!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!

# Чтобы следовать принципу открытости/закрытости, можно вместо изменения существующего класса использовать наследование или полиморфизм для расширения функциональности.


from abc import ABC, abstractmethod

# Базовый абстрактный класс для сотрудников
class Employee(ABC):
    def __init__(self, name):
        self.name = name

    @abstractmethod
    def calculate_salary(self):
        pass

# Класс для сотрудников уровня Junior
class Junior(Employee):
    def calculate_salary(self):
        return 50000

# Класс для сотрудников уровня Middle
class Middle(Employee):
    def calculate_salary(self):
        return 100000

# Класс для сотрудников уровня Senior
class Senior(Employee):
    def calculate_salary(self):
        return 150000

# Использование
employees = [Junior("Alex"), Middle("John"), Senior("Eve")]

for employee in employees:
    print(f"{employee.name} получает {employee.calculate_salary()} рублей")


# Преимущества применения OCP:
    # Модульность: Код становится легче расширять. Если нам нужно добавить новую позицию (например, Lead), мы просто создаем новый 
    # класс Lead и реализуем в нем метод calculate_salary, не трогая уже существующий код.
    
    # Поддерживаемость: Изменение в одном месте не повлияет на другие части программы, что снижает риск ошибок.
    
    # Тестируемость: Классы можно легко тестировать отдельно друг от друга, что делает тестирование более изолированным.


# Когда OCP особенно полезен:
    # Когда система постоянно развивается, и нужно часто добавлять новые функции, не затрагивая основной код.
    # В проектах с большой кодовой базой, где изменение существующего кода может привести к непредвиденным последствиям и багам.

# Заключение:
    # Принцип открытости/закрытости улучшает качество кода, делая его более гибким и защищенным от поломок при внесении изменений. 
    # Следуя OCP, мы можем добавлять новый функционал, не изменяя существующий код, что делает систему более устойчивой и масштабируемой.



