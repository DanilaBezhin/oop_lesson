# ==============================================================================================
# SINGLE RESPONSIBILITY PRINCIPLE

# Принцип единой ответственности (Single Responsibility Principle, SRP) — это один из принципов SOLID, который утверждает, что каждый класс или функция 
# должна иметь одну и только одну ответственность. То есть, класс или функция должны быть сосредоточены на выполнении одной задачи.

# Это важно, потому что код становится более читабельным, легче поддерживается и тестируется.


# Без этого принципа мы создали такое:
class User:
    def __init__(self, name, email):
        self.name = name
        self.email = email

    def save_to_database(self):
        print(f"Сохраняем пользователя {self.name} в базу данных...")

    def send_email(self):
        print(f"Отправляем письмо на {self.email}...")

# Использование
user = User("Alex", "alex@example.com")
user.save_to_database()
user.send_email()

# Здесь класс User отвечает сразу за несколько вещей:
    # Создание пользователя с именем и email.
    # Сохранение данных пользователя в базу.
    # Отправка email.
# Это нарушает принцип единой ответственности, потому что класс делает сразу несколько вещей: управляет пользователями и отвечает за взаимодействие с 
# базой данных и отправку писем. Это делает код сложнее для модификации — если нужно изменить логику отправки писем или сохранения данных, нужно менять код самого класса User.



# С реализацией этого принципа !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
class User:
    def __init__(self, name, email):
        self.name = name
        self.email = email

class UserDatabase:
    def save(self, user):
        print(f"Сохраняем пользователя {user.name} в базу данных...")

class EmailService:
    def send(self, user):
        print(f"Отправляем письмо на {user.email}...")

# Использование
user = User("Alex", "alex@example.com")
db = UserDatabase()
email_service = EmailService()

db.save(user)            # Сохранение пользователя в базу данных
email_service.send(user)  # Отправка email пользователю

# Теперь каждый класс выполняет только одну задачу:
    # User: хранит информацию о пользователе (имя и email). Этот класс не знает ничего о базах данных и отправке писем.
    # UserDatabase: отвечает за сохранение пользователей в базу данных.
    # EmailService: занимается отправкой писем.

# Заключение:
# Принцип единой ответственности помогает сделать код чище и модульнее. Каждая часть системы занимается только своим делом, 
# что упрощает внесение изменений, тестирование и улучшает понимание кода.



