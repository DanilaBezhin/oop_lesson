# LISKOV SUBSTITUTION PRINCIPLE


# Принцип подстановки Барбары Лисков (Liskov Substitution Principle, LSP) — это третий принцип из SOLID, который гласит, 
# что объекты базового класса должны заменяться объектами его подклассов без нарушения корректности работы программы.

# Иными словами, если класс B является наследником класса A, то объекты B должны вести себя так же, как и объекты A. 
# Это означает, что код, работающий с объектами базового класса A, должен продолжать корректно работать, 
# если вместо них использовать объекты класса B, не требуя изменений.


# Пример нарушения LSP
class Rectangle:
    def __init__(self, width: int, height: int):
        self.width = width
        self.height = height

    def set_width(self, width: int):
        self.width = width

    def set_height(self, height: int):
        self.height = height

    def area(self):
        return self.width * self.height

# Класс Квадрат наследуется от Прямоугольника
class Square(Rectangle):
    def set_width(self, width: int):
        self.width = width
        self.height = width  # Квадрат должен иметь одинаковые стороны

    def set_height(self, height: int):
        self.width = height  # Квадрат должен иметь одинаковые стороны
        self.height = height

# На первый взгляд, кажется логичным наследовать квадрат от прямоугольника, так как квадрат — это частный случай прямоугольника, у которого все стороны равны.


# Теперь представим, что есть функция для вычисления площади прямоугольников:
# def calculate_area(rectangle: Rectangle):
#     rectangle.set_width(5)
#     rectangle.set_height(10)
#     assert rectangle.area() == 50, "Ошибка: площадь не соответствует ожиданиям"


# Проблема:
# Если мы передадим объект класса Square в функцию calculate_area, она не будет работать правильно. Это нарушает принцип LSP, 
# потому что объект подкласса Square не может заменить объект базового класса Rectangle без изменения логики.
# square = Square(5, 5)
# calculate_area(square)  # Ошибка, т.к. для квадрата ширина и высота всегда равны



# Исправление с учетом LSP !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!

# Чтобы соблюсти принцип подстановки Лисков, нужно пересмотреть иерархию классов. Квадрат не должен наследоваться от прямоугольника, 
# потому что он ведет себя иначе, даже если это геометрически частный случай прямоугольника. Один из способов решения — использовать композицию, а не наследование:

# Композиция — это принцип объектно-ориентированного программирования, при котором объекты одного класса содержат объекты других классов для реализации своей функциональности. 
# Вместо того, чтобы наследовать от класса, объект использует объекты других классов для выполнения своих задач. 
# Композиция используется, когда есть отношения "имеет", например: "Машина имеет двигатель".

# Композиция полезна, когда один класс зависит от функциональности другого, но при этом не обязательно наследовать его поведение, как в случае с наследованием. 
# Это также помогает делать код более гибким и модульным.

class Rectangle:
    def __init__(self, width: int, height: int):
        self.width = width
        self.height = height

    def set_width(self, width: int):
        self.width = width

    def set_height(self, height: int):
        self.height = height

    def area(self):
        return self.width * self.height

class Square:
    def __init__(self, side_length: int):
        self.rectangle = Rectangle(side_length, side_length)

    def set_side_length(self, side_length: int):
        self.rectangle.set_width(side_length)
        self.rectangle.set_height(side_length)

    def area(self):
        return self.rectangle.area()

# Теперь классы Rectangle и Square разделены, и они работают независимо. 
# Квадрат использует композицию, чтобы использовать поведение прямоугольника, при этом сохраняя свои уникальные свойства.




# Пример с использованием интерфейсов
# Предположим, у нас есть класс для работы с файлами:

# Интерфейс в программировании
# Интерфейс — это набор методов (функций), которые класс должен реализовать. Интерфейсы помогают определить, какие методы должен иметь класс, но не указывают, 
# как именно эти методы должны быть реализованы. Интерфейсы полезны для того, чтобы разные классы могли иметь одинаковую "оболочку", 
# но реализовывать логику этих методов по-разному.

# ВАЖНО: В Python нет явных интерфейсов, как в других языках, таких как Java. Однако интерфейсы можно реализовать через абстрактные базовые классы (ABC) 
# или просто через соглашение, что класс должен реализовать определенные методы.

class File:
    def read(self):
        pass

    def write(self, data):
        pass

class ReadOnlyFile(File):
    def read(self):
        return "Чтение файла"

    def write(self, data):
        raise NotImplementedError("Нельзя записывать в этот файл")

# Проблема:
# Этот код нарушает LSP, так как ReadOnlyFile нельзя использовать там, где ожидается обычный файл, поскольку операция записи вызывает исключение. 
# Если код, работающий с объектом File, попытается вызвать метод write, он будет работать некорректно для объекта ReadOnlyFile.


# Исправление с учетом LSP !!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
# Вместо этого можно разделить интерфейс на два отдельных: для чтения и для записи.

class Readable:
    def read(self):
        
        pass

class Writable:
    def write(self, data):
        pass

class File(Readable, Writable):
    def read(self):
        return "Чтение файла"

    def write(self, data):
        print("Запись в файл")

class ReadOnlyFile(Readable):
    def read(self):
        return "Чтение только для чтения"


# Теперь классы не нарушают принцип LSP, так как каждый класс реализует только те методы, которые для него имеют смысл.

# Заключение
# Принцип подстановки Лисков помогает создавать гибкие и надежные системы, где подклассы могут свободно использоваться вместо базовых классов, 
# не нарушая логику работы программы. Соблюдение этого принципа делает систему предсказуемой, поддерживаемой и расширяемой.