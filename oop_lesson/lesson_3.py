class Person: 
    # Магический метод инициализации
    def __init__(self, name, age, gender):
        self.name = name
        self.age = age
        self.gender = gender

    # Магический метод (финализатор) (вызывается перед уничтожением экземпляра класса))
    # Пока на объект ведет хотя бы 1 внешняя ссылка он считается нужным, если не нужен автоматически удаляется сборщиком мусора
    # Например если изменить (person_1 = Person(...)) на (person_1 = None) вызовется __del__
    def __del__(self):
        print(f"Person {self.name} deleted")

    def info(self):
        print(f"Name: {self.name}, age: {self.age}, gender: {self.gender}")

person_1 = Person("John", 20, "m")
person_2 = Person("Jane", 25, "w")

del person_1

person_2.info()
person_2 = None


person_list = []
for i in range(3):
    p = Person(f'user{i}', i, 'm')
    person_list.append(p)

print(person_list)

print('end')


