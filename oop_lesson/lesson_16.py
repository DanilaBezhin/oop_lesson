
# В Python hash — это встроенная функция, которая возвращает хэш-значение объекта. 
# Хэш-значение — это целое число, которое вычисляется на основе содержимого объекта 
# и используется для быстрого сравнения и поиска. 
# Основная цель хэш-функции — преобразование данных в фиксированный размер числа, которое затем можно использовать, 
# например, в хэш-таблицах (например, в словарях).

# Важный моменты
    # Непостоянность хэш-значений между запусками: В Python 3 хэш-значения строк и других объектов изменяются при 
    # каждом запуске программы (для повышения безопасности).

    # Хэшируемость объекта: Объект должен быть неизменяемым (например, строки, кортежи) и 
    # реализовать метод __hash__, чтобы его можно было хэшировать.

    # Использование хэшей в словарях и множествах: Хэш-значения объектов используются для быстрого доступа к элементам в 
    # словарях и множествах. Обратите внимание, что изменяемые объекты, такие как списки и словари, не могут быть хэшируемыми, 
    # так как их содержимое может изменяться, что нарушает основное требование для хэш-значений — неизменяемость.


# Как работает хэширование в словарях и множествах

# Словари (dict):
    # Словарь в Python хранит пары "ключ-значение". Когда вы добавляете новую пару, 
    # Python вычисляет хэш-значение ключа с помощью функции hash.

    # Это хэш-значение определяет, куда в памяти будет помещен элемент (называется "бакетом"). 
    # Это позволяет Python мгновенно находить место для хранения пары ключ-значение.
    
    # Когда вы пытаетесь получить значение по ключу, Python повторно вычисляет хэш-значение ключа и находит соответствующий бакет, 
    # где хранится значение. Это делает доступ к элементу очень быстрым, в среднем за постоянное время — O(1).

    # пример
    # d = {"apple": 1, "banana": 2, "cherry": 3}
    # value = d["banana"]  # Python вычисляет хэш "banana" и находит соответствующий элемент.

    # именно поэтому словари в качеству ключей принимаю только неизменяемые значения


# Множества (set):
    # Множество хранит только уникальные элементы, и Python использует хэш-значения, чтобы гарантировать уникальность.

    # Когда вы добавляете элемент в множество, Python вычисляет его хэш-значение и проверяет, есть ли уже такой хэш в множестве. 
    # Если хэш совпадает с существующим, Python проверяет сам объект (например, если это другой объект с таким же хэш-значением).
    # Если нет совпадений, элемент добавляется в множество.

    # Поиск и удаление элементов также основаны на хэш-значениях, что делает операции над множествами очень быстрыми.
    
    # Пример:
    # s = {1, 2, 3}
    # s.add(4)  # Python вычисляет хэш 4 и добавляет его, если его еще нет.


# Проблемы с хэшированием
    # Коллизии: Иногда разные объекты могут иметь одинаковые хэш-значения. Это называется коллизией. 
    # Python решает коллизии с помощью различных методов, например, цепочек (хранение нескольких элементов в одном бакете) 
    # или пробинга (поиск следующего доступного бакета).

    # Изменяемые объекты: Объекты, которые могут изменяться (например, списки), не могут быть хэшируемыми, 
    # потому что изменение их значений нарушит логику хэширования.

# Хэширование — это то, что делает словари и множества в Python одними из самых быстрых структур данных для поиска и работы с данными.


# Как устроены списки в Python
# В Python список — это динамический массив. Это означает, что список состоит из последовательных блоков памяти, 
# каждый из которых содержит ссылку на элемент списка.

# Механизм доступа по индексу
    # Непрерывный блок памяти:
        # Список хранит элементы последовательно в непрерывном блоке памяти. Это значит, что Python знает точный адрес памяти начала списка.
        # Каждый элемент в списке занимает определённое количество байтов (размер указателя на объект).
    
    # Арифметический расчет адреса:
        # Когда вы обращаетесь к элементу по индексу, Python использует арифметику указателей для быстрого вычисления места, где находится этот элемент.
        # Например, если вы хотите получить элемент по индексу i, Python вычисляет адрес памяти для этого элемента как начальный_адрес + (i * размер_элемента).

    # Прямой доступ:
        # Этот процесс требует только одной арифметической операции, что делает доступ к элементу очень быстрым, с постоянной сложностью O(1).

    # Пример работы
    # Предположим, у вас есть список:
    # lst = [10, 20, 30, 40]
    # Когда вы делаете lst[2], Python вычисляет адрес элемента:

    # 1 Начальный адрес — это адрес первого элемента (10).
    # 2 Размер каждого элемента фиксирован.
    # 3 Индекс 2 указывает на третий элемент (30).
    # 4 Python просто добавляет смещение для вычисления адреса третьего элемента и мгновенно получает его значение.
    
# Отличие от словарей
    # Хотя и доступ по индексу в списке, и доступ по ключу в словаре имеют сложность O(1), их механизмы работы различаются. В списке Python просто использует арифметику для доступа к элементу, в то время как в словаре вычисляется и используется хэш-значение.

# Таким образом, основная причина того, что доступ по индексу происходит за O(1) — это непрерывное расположение элементов в памяти и простая арифметика указателей.



# Функция hash() - возвращает хэш-значение объекта
# Хэш-значение — это целое число, которое вычисляется на основе содержимого объекта 

# print(hash("Python")) # -> 362837564120375479
# print(hash("Python")) # -> 362837564120375479
# print(hash(10)) # -> 10
# print(hash((10, 20, 30))) # -> 3952409569436607343
# print(hash((310, 120, 20))) # -> 8238794076684169193

# утверждения 

# Если объекты: a == b (равны), то равен и их хэш
# Равные хеши: hash(a) == hash(b), не гарантируют равенство объектов
# Если хеши не равны: hash(a) != hash(b), то объекты точно не равны 

# при попытке вычислить hash изменяемого объекта, мы получим ошибку
# TypeError: unhashable type: type*
# my_dict = {}
# my_dict[{231}] = 1
# print(my_dict)

class Point:
    def __init__(self, x, y):
        self.x = x
        self.y = y

    def __eq__(self, other):
        return self.x == other.x and self.y == other.y
    
    def __hash__(self):
        return hash((self.x, self.y))
    

p1 = Point(1, 2)
p2 = Point(1, 2)

print(p1 == p2)

# можно вычислить хэш тк объекты пользовательского класса воспринимаются как неизменяемые 
# (пока мы не определим __eq__ для сравнения координат точек)
# print(hash(p1) == hash(p2))
# что бы поправить ситуацию можем переопределить магический метод __hash__
# теперь hash будет высчитываться для кортежа координат, к примеру(1, 2)
print(hash(p1), hash(p2), sep="\n")



# этот пример говорит о том, что теперь объекты p1 и p2 воспринимаются как один и тот же ключ
# поскольку их хеши равны. Если закомментировать магические методы __eq__ и __hash__ такой код
# будет работать иначе, воспринимая данные объекты как разные ключи (тк по умолчанию эта два разных объекта)
# {<__main__.Point object at 0x0000023E9F934220>: 1, <__main__.Point object at 0x0000023E9F937880>: 2}
d = {}
d[p1] = 1
d[p2] = 2
