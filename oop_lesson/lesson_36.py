#  Пример метакласса
# Теперь давайте создадим собственный метакласс. Метаклассы создаются так же, как и обычные классы, но наследуются от type:


class MyMeta(type):
    def __new__(cls, name, bases, dct):
        print(f"Создание класса {name}")
        return super().__new__(cls, name, bases, dct)


# Что здесь происходит:
# __new__ — это метод, который создаёт и возвращает новый класс. Он вызывается до инициализации объекта (в нашем случае — класса).
# cls — это сам метакласс.
# name — имя создаваемого класса.
# bases — это базовые классы, от которых наследуется новый класс.
# dct — это словарь атрибутов и методов класса.


# Теперь давайте создадим класс с этим метаклассом:

class MyClass(metaclass=MyMeta):
    pass


# Когда Python видит такой код, он делает следующее:

# Вызывает метакласс MyMeta.

# Передаёт в __new__ метакласса имя класса (MyClass), базовые классы (в данном случае их нет) и атрибуты класса 
# (в данном случае это пустой словарь, потому что нет методов или атрибутов).

# Метакласс создаёт новый класс, печатает сообщение "Создание класса MyClass".


# Пример полезного использования метаклассов:

# Давайте создадим метакласс, который автоматически добавляет метод hello каждому классу, который он создаёт:


class AddHelloMeta(type):
    def __new__(cls, name, bases, dct):
        dct['hello'] = lambda self: print("Hello from", self.__class__.__name__)
        return super().__new__(cls, name, bases, dct)


class MyClass(metaclass=AddHelloMeta):
    pass

obj = MyClass()
obj.hello()  # Выведет: Hello from MyClass



