# мета класс, на подобии django orm

class Meta(type):
    def create_local_attrs(self, *args, **kwargs):
        for key, value in self.class_attrs.items():
            self.__dict__[key] = value
    
    def __init__(cls, name, base, attrs):
        print(f"cls: {cls}, name: {name}, base: {base}, attrs: {attrs}")
        cls.class_attrs = attrs
        cls.__init__ = Meta.create_local_attrs

class Women(metaclass=Meta):
    title = "women"
    content = "women content"
    photo = "women photo"


w = Women()
print(w.__dict__)



# Что такое метакласс?

# Метакласс — это "класс для классов". Если обычный класс создаёт объекты, то метакласс создаёт классы. Другими словами, метакласс контролирует, как создаются классы.

# По умолчанию, когда мы создаём класс в Python, Python использует встроенный метакласс type. Это значит, что при создании любого класса на самом деле происходит вызов type:
# Это делает Python под капотом:
# MyClass = type('MyClass', (), {})



# Как работает type
# type может делать две вещи:

# Создавать классы: Когда вы вызываете type с тремя аргументами, он создаёт новый класс:
# MyClass = type('MyClass', (), {})
# 'MyClass' — имя класса.
# () — кортеж базовых классов, от которых будет наследоваться новый класс.
# {} — это словарь атрибутов и методов нового класса.

# Возвращать тип объекта: Когда вы вызываете type с одним аргументом, он возвращает тип объекта (его класс):
# print(type(5))  # <class 'int'>



