class Person: 
    "This is a Person class"
    age = 10
    name = "John"

a = Person()
print(a.age)
print(a.name)

b = Person()
print(b.age)
print(b.name)

# Изменяет значение атрибута, даже у экземпляров класса, так как те в свою очередь ссылаются на атрибуты класса Person
Person.age = 20
print(a.age)
print(b.age)

# Возвращает значение атрибута объекта, если его нет то возвращает False
print(f"Getattr: {getattr(a, 'les', False)}") 

# Возвращает True если атрибут существует
print(f"Hasattr: {hasattr(Person, 'age')}")

# Устанавливает значение атрибута объекта, если его нет то создает его
setattr(a, 'height', 160)
print(a.height)

# Удаляет атрибут, выдает ошибку если его нет
delattr(a, 'height')
# print(a.height)

# Содержит набор атрибутов экземпляра класса, в данном случае ничего, так как 'a' не содержит никаких атрибутов, а ссылается на класс Person
print(a.__dict__)

# Возвращает документацию класса. Экземпляр так же возвращает документацию класса
print(Person.__doc__)
print(a.__doc__)



