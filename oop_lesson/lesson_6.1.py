# Выжимка по теме
# 1. Что такое инкапсуляция?

# Инкапсуляция — это один из принципов ООП, ограничивающий доступ к данным объекта. Она позволяет:

# скрывать внутренние детали реализации;
# предотвращать некорректное изменение данных;
# контролировать доступ к методам.


# В Python инкапсуляция реализуется через уровни доступа:

# Открытые (public) атрибуты и методы: доступны отовсюду (self.x);
# Защищенные (protected): обозначаются одним подчеркиванием (self._x), не запрещены, но считаются внутренними;
# Приватные (private): обозначаются двойным подчеркиванием (self.__x), скрываются от прямого доступа.


# 2. Библиотека accessify
# accessify — это сторонняя библиотека, расширяющая стандартные механизмы инкапсуляции в Python. Она позволяет жестко ограничивать доступ к 
# методам и атрибутам, используя декораторы:

# @private — делает метод полностью закрытым даже от вызова через self._Class__method().
# @protected — позволяет вызывать метод только внутри класса и его наследников.


# 3. Устанавливается ли accessify отдельно?
# Да, библиотека accessify не является встроенной в Python. Ее нужно установить через pip:

# pip install accessify
# После установки можно использовать декораторы @private и @protected для лучшей защиты кода.


# 4. В чем преимущество accessify?

# В отличие от обычных __private атрибутов, @private полностью блокирует доступ даже через обходные пути.
# @protected дает строгий контроль, позволяя наследникам работать с методом, но блокируя его извне.
# Это полезно, если код требует строгой защиты данных (например, в банковских или медицинских системах).
# Таким образом, accessify усиливает стандартные механизмы инкапсуляции Python, помогая создавать более надежные и защищенные классы.


