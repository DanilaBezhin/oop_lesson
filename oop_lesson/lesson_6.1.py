# Используйте @private из accessify, чтобы создать приватный метод __validate_password(password), который проверяет, является ли пароль строкой и содержит ли он не менее 6 символов.

# Реализуйте методы:
# change_password(new_password): изменяет пароль, проверяя его через __validate_password(new_password).
# get_username(): возвращает логин пользователя.

# Проверьте, что при попытке вызвать __validate_password() напрямую снаружи класса возникает ошибка.
# Дополнительно: Попробуйте изменить пароль на слишком короткий и убедитесь, что код корректно выбрасывает исключение.



from accessify import private

class User:
    def __init__(self, username, password):
        self.__username = username
        if self.__validate_password(password):  # Проверяем пароль при создании объекта
            self.__password = password
        else:
            raise ValueError("Пароль должен быть строкой не короче 6 символов")

    @private
    def __validate_password(self, password):
        """Проверяет, что пароль - строка длиной не менее 6 символов."""
        return isinstance(password, str) and len(password) >= 6

    def change_password(self, new_password):
        """Позволяет изменить пароль, если он соответствует требованиям."""
        if self.__validate_password(new_password):
            self.__password = new_password
            print("Пароль успешно изменен")
        else:
            raise ValueError("Новый пароль должен быть строкой не короче 6 символов")

    def get_username(self):
        """Возвращает логин пользователя."""
        return self.__username


# --- Тестирование класса ---
user = User("test_user", "secure123")  # Создание объекта с корректным паролем
print(user.get_username())  # Выводит: test_user

user.change_password("newpass")  # Пароль успешно изменен

