# Когда стоит использовать dataclass?
    # Когда вам нужно создать класс, который просто хранит данные, а его основной задачей является удобное представление структуры данных.
    # Когда вам нужно минимизировать шаблонный код, связанный с инициализацией и сравнением объектов.
    # Когда вам важна поддержка статической типизации, и вы хотите, чтобы классы с данными были легко читаемы и поддерживаемы.


