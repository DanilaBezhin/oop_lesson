# Введение в Data Classes

class Thing:
    def __init__(self, name, year, price=0, author=[]):
        self.name = name
        self.year = year
        self.price = price
        self.author = author

    def __repr__(self):
        return f'Thing({self.__dict__})'

t = Thing('Python к вершинам мастерства', 2022, 799)
t.author.append('Alex')
print(t) # Thing({'name': 'Python к вершинам мастерства', 'year': 2022, 'price': 799, 'author': ['Alex']})
t2 = Thing('Python к вершинам мастерства', 2022, 799)
print(t2) # Thing({'name': 'Python к вершинам мастерства', 'year': 2022, 'price': 799, 'author': ['Alex']})


