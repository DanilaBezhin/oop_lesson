# Основные параметры field()
    # default: Задает значение по умолчанию для поля.
    # default_factory: Фабрика для создания значения по умолчанию (полезно для изменяемых типов данных, таких как списки).
    # init: Если False, это поле не будет использоваться в методе __init__().
    # repr: Если False, поле не будет отображаться в строковом представлении объекта (__repr__()).
    # compare: Если False, поле не будет участвовать в сравнении объектов (не будет учтено в методах __eq__(), __lt__(), и т.д.).
    # hash: Если False, поле не будет участвовать в хешировании объекта (в методе __hash__()).
    # metadata: Служебные данные, которые могут быть полезны для обработки полей (редко используется).


from dataclasses import dataclass, field

@dataclass
class Book:
    title: str
    # Использование default_factory для изменяемых типов
    authors: list[str] = field(default_factory=list)
    pages: int
    # Поле со значением по умолчанию
    price: float = field(default=10.0)  # значение по умолчанию

book = Book("1984", "George Orwell", 328)
print(book)  
