class Animal:
    def __init__(self, name):
        self.name = name

    def speak(self):
        return f"{self.name} makes a sound"

class Dog(Animal):
    def __init__(self, name, breed):
        # Вызов __init__ родительского класса с помощью super()
        super().__init__(name)
        self.breed = breed

    def speak(self):
        # Вызов метода speak() родительского класса с помощью super()
        parent_speak = super().speak()
        return f"{parent_speak} and barks"

# Пример использования
dog = Dog("Buddy", "Golden Retriever")
print(dog.speak())




