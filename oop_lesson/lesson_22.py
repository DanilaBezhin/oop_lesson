class Geom:
    name = 'Geom'

    def __init__(self, x, y):
        print(f'Geom: __init__ for class {self.__class__}')
        self.x = x
        self.y = y


class Line(Geom):
    name = 'Line'

    def draw(self):
        print(f'Geom: {self.name}: draw line')


class Rect(Geom):
    name = 'Rect'

    def __init__(self, x, y, w, h):
        print(f'Rect: __init__')
        # писать так не лучшая практика но работает
        # Geom.__init__(self, x, y)

        # лучший вариант написать super()
        # вызов методов базового класса через функцию super называется делегированием 
        super().__init__(x, y)

        self.w = w
        self.h = h
        


    def draw(self):
        print(f'Geom: {self.name}: draw rect')


