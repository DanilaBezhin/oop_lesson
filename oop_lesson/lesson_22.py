# Инициализация объектов в наследовании:
    # Когда дочерний класс наследует родительский, он может использовать метод __init__ родительского класса для инициализации общих атрибутов.
    # Если дочерний класс переопределяет метод __init__, то вызов метода __init__ родительского класса нужно выполнять явно.

# Способы вызова методов родительского класса:
    # Прямой вызов через имя класса:
    # Например, Geom.__init__(self, x, y). Это работает, но считается менее гибким и не рекомендуется, так как может привести к ошибкам при изменении структуры наследования.
    # Вызов через super():
    # Например, super().__init__(x, y). Это современный и предпочтительный способ, который автоматически определяет правильный родительский класс и обеспечивает более гибкое наследование.

# Делегирование:
    # Использование super() для вызова методов базового класса называется делегированием . Это позволяет избежать жесткой привязки к конкретному родительскому классу и делает код более поддерживаемым.

# Переопределение методов:
    # Дочерний класс может переопределять методы родительского класса, добавляя или изменяя их функциональность.
    # При этом можно вызвать метод родительского класса внутри переопределенного метода с помощью super() для повторного использования его логики.



