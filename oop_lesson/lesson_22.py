# Задание: Создайте класс UniqueList, который хранит только уникальные элементы.
class UniqueList(list):
    def append(self, value):
        if value not in self:
            super().append(value)

# Пример использования:
ul = UniqueList()
ul.append(1)
ul.append(2)
ul.append(1)
print(ul)  # Вывод: [1, 2]