# ==============================================================================================
# INTERFACE SEGREGATION PRINCIPLE

# Принцип разделения интерфейса (Interface Segregation Principle, ISP) является одним из пяти принципов SOLID, 
# используемых в объектно-ориентированном программировании для создания гибких и поддерживаемых систем. 
# Этот принцип утверждает, что клиенты не должны зависеть от интерфейсов, которые они не используют. 
# Другими словами, интерфейсы должны быть специализированными и содержать только те методы, которые нужны клиентам, использующим их.


# Основная идея ISP:
    # Лучше несколько маленьких, узкоспециализированных интерфейсов, чем один "толстый" интерфейс с множеством методов.
    # Классы не должны быть вынуждены реализовывать методы, которые им не нужны.


# Пример без ISP:
# Предположим, у нас есть большой интерфейс Worker с методами, которые должны быть реализованы всеми рабочими, но не все из них нужны каждому конкретному классу.


class Worker:
    def work(self):
        pass

    def eat(self):
        pass

class HumanWorker(Worker):
    def work(self):
        print("Работаю")

    def eat(self):
        print("Обедаю")

class RobotWorker(Worker):
    def work(self):
        print("Работаю")
    
    # Роботы не едят, но мы вынуждены реализовать этот метод
    def eat(self):
        raise NotImplementedError("Роботы не едят!")

# Проблема:
# Здесь у нас есть интерфейс Worker, который предполагает, что каждый рабочий должен уметь как работать, так и есть. 
# Но для робота метод eat не нужен, и поэтому приходится бросать исключение или оставлять метод пустым.



# Пример с ISP!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
# С принципом разделения интерфейса мы можем разделить один "толстый" интерфейс на несколько узкоспециализированных, 
# чтобы каждый класс реализовывал только нужные ему методы.


# Определяем более узкие интерфейсы
class Workable:
    def work(self):
        pass

class Eatable:
    def eat(self):
        pass

# Человеческий работник реализует оба интерфейса
class HumanWorker(Workable, Eatable):
    def work(self):
        print("Работаю")

    def eat(self):
        print("Обедаю")

# Робот реализует только тот интерфейс, который ему нужен
class RobotWorker(Workable):
    def work(self):
        print("Работаю")


# Теперь интерфейсы разделены на Workable и Eatable, и каждый класс реализует только те интерфейсы, которые ему нужны. 
# HumanWorker реализует оба интерфейса, потому что человек и работает, и ест, а RobotWorker — только интерфейс работы.


# Преимущества ISP:
    # Упрощение кода: Классы становятся проще, так как они реализуют только необходимые методы.
    # Повышение гибкости: Легче изменять или добавлять функциональность, так как интерфейсы становятся более модульными.
    # Улучшение поддерживаемости: Изменение интерфейса в будущем затронет только те классы, которые его используют, а не все классы сразу.
    # Повышение читабельности: Меньше методов в интерфейсе — лучше понимание для разработчиков, которые его используют.


# Заключение:
    # Принцип разделения интерфейса помогает избежать больших универсальных интерфейсов, которые могут содержать множество ненужных методов для конкретных реализаций. 
    # Разделяя интерфейсы на более маленькие и специализированные, можно создать более чистую и поддерживаемую систему, в которой классы реализуют только те методы, 
    # которые им действительно нужны.



