# DEPENDENCY INVERSION PRINCIPLE 

# Принцип инверсии зависимостей (Dependency Inversion Principle, DIP) является одним из пяти ключевых принципов SOLID в объектно-ориентированном программировании. 
# Он утверждает, что модули верхнего уровня (высокоуровневые компоненты) не должны зависеть от модулей нижнего уровня (низкоуровневых компонентов). 
# Вместо этого оба типа модулей должны зависеть от абстракций. Также, абстракции не должны зависеть от деталей, но детали должны зависеть от абстракций.

# Основная идея DIP:
    # Модули верхнего уровня — это те, которые определяют высокоуровневую логику и поведение системы. Например, это может быть бизнес-логика приложения.
    # Модули нижнего уровня — это модули, которые реализуют конкретные детали, такие как работа с базой данных, чтение файлов и т.д.

# Важный момент — избегать зависимости высокоуровневой логики от низкоуровневых деталей. Это делает систему гибче, легче тестируется и поддерживается, 
# так как можно изменять конкретные реализации (например, тип базы данных), не затрагивая логику верхнего уровня.


# Пример нарушения DIP:
# Представим систему, в которой класс EmailNotification отвечает за отправку уведомлений пользователям.

class EmailService:
    def send_email(self, message: str):
        print(f"Отправка email с сообщением: {message}")

class EmailNotification:
    def __init__(self):
        self.email_service = EmailService()  # Прямая зависимость от конкретного класса

    def notify(self, message: str):
        self.email_service.send_email(message)

# В этом примере класс EmailNotification напрямую зависит от класса EmailService. 
# Если мы захотим отправлять уведомления через другой сервис (например, SMS или push-уведомления), нам придется менять код внутри EmailNotification,
#  что нарушает принцип открытости-закрытости (Open/Closed Principle).


# Пример с использованием DIP!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
# Чтобы следовать принципу инверсии зависимостей, необходимо ввести абстракцию, от которой будут зависеть оба класса, 
# а не напрямую связывать высокоуровневую логику с конкретными реализациями.

# Абстракция для сервиса уведомлений
from abc import ABC, abstractmethod

class NotificationService(ABC):
    @abstractmethod
    def send(self, message: str):
        pass

# Конкретная реализация через email
class EmailService(NotificationService):
    def send(self, message: str):
        print(f"Отправка email с сообщением: {message}")

# Конкретная реализация через SMS
class SMSService(NotificationService):
    def send(self, message: str):
        print(f"Отправка SMS с сообщением: {message}")

# Класс уведомлений зависит от абстракции
class Notification:
    def __init__(self, service: NotificationService):
        self.service = service

    def notify(self, message: str):
        self.service.send(message)


# Теперь Notification зависит от абстракции NotificationService, а не от конкретной реализации, такой как EmailService или SMSService. 
# Это дает гибкость: если нужно сменить сервис, мы просто передаем новую реализацию абстракции в конструктор.


# Преимущества DIP:
    # Гибкость: Высокоуровневый код не привязан к конкретной реализации низкоуровневых модулей. Это позволяет легко заменять или изменять детали реализации, 
    # не затрагивая основную логику.
    
    # Тестируемость: Легче подменять конкретные реализации на "заглушки" или "моки" при написании тестов, что упрощает юнит-тестирование.
    
    # Поддерживаемость: Изменения в коде, связанные с конкретными реализациями, не требуют изменения в логике верхнего уровня, что делает систему более устойчивой к изменениям.
    
    # Модульность: Код становится лучше структурированным и разбитым на независимые модули, что упрощает его поддержку и развитие.


# Пример внедрения зависимостей:
email_service = EmailService()
notification = Notification(email_service)  # Внедрение зависимости через конструктор
notification.notify("Hello, world!")

# Этот подход делает код гибким и легко адаптируемым для работы с различными зависимостями.


# Заключение:
# Принцип инверсии зависимостей направлен на то, чтобы разделять высокоуровневые и низкоуровневые модули через абстракции. 
# Это делает код более гибким, легче тестируемым и поддерживаемым, устраняя жесткие связи между конкретными реализациями.